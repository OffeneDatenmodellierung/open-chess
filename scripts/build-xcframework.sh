#!/usr/bin/env bash
# Build the iOS app's core (crates/chess-mobile) as a Swift package: an
# xcframework of the static library for iPhone/iPad and the Apple-silicon
# simulator, and the Swift bindings UniFFI generates for it.
#
#   scripts/build-xcframework.sh [OUT_DIR]      (default: dist/ios)
#
# On a Mac with Xcode. The release workflow runs it on tags; locally,
# point the app's Xcode project at OUT_DIR/OpenChessCore as a local
# package. METAL=1 builds the board reader for the GPU (default: the CPU).
set -euo pipefail
cd "$(dirname "$0")/.."
out=${1:-dist/ios}

if [[ "$(uname)" != Darwin ]] || ! command -v xcodebuild >/dev/null; then
  echo "needs macOS with Xcode (xcodebuild)" >&2
  exit 1
fi

targets=(aarch64-apple-ios aarch64-apple-ios-sim)
if command -v rustup >/dev/null; then
  rustup target add "${targets[@]}" >/dev/null
fi

features=()
if [[ "${METAL:-0}" == 1 ]]; then features=(--features metal); fi

# The release profile strips symbols, which would take the library's
# exported functions with them: keep them (Xcode strips the app).
export CARGO_PROFILE_RELEASE_STRIP=none

# The oldest iOS the app supports.
export IPHONEOS_DEPLOYMENT_TARGET=${IPHONEOS_DEPLOYMENT_TARGET:-17.0}

for t in "${targets[@]}"; do
  cargo build --release --locked -p open-chess-mobile --lib --target "$t" ${features[@]+"${features[@]}"}
done

# The bindings come from the library's metadata: build it for this Mac
# and ask the bindgen about it.
cargo build --release --locked -p open-chess-mobile --lib ${features[@]+"${features[@]}"}
cargo build --release --locked -p open-chess-mobile --features bindgen --bin uniffi-bindgen
gen=$(mktemp -d)
target/release/uniffi-bindgen generate --library target/release/libopen_chess_mobile.dylib \
  --language swift --out-dir "$gen"

pkg=$out/OpenChessCore
rm -rf "$pkg"
mkdir -p "$pkg/Sources/OpenChessCore" "$gen/headers"
cp "$gen"/*.h "$gen/headers/"
# Xcode looks for this name inside an xcframework's headers.
cp "$gen"/*.modulemap "$gen/headers/module.modulemap"
cp "$gen"/*.swift "$pkg/Sources/OpenChessCore/"

args=()
for t in "${targets[@]}"; do
  args+=(-library "target/$t/release/libopen_chess_mobile.a" -headers "$gen/headers")
done
xcodebuild -create-xcframework "${args[@]}" -output "$pkg/open_chess_mobileFFI.xcframework"

cat > "$pkg/Package.swift" <<'SWIFT'
// swift-tools-version:5.9
// Generated by scripts/build-xcframework.sh: the open-chess core for iOS.
import PackageDescription

let package = Package(
    name: "OpenChessCore",
    platforms: [.iOS(.v17)],
    products: [.library(name: "OpenChessCore", targets: ["OpenChessCore"])],
    targets: [
        .binaryTarget(name: "open_chess_mobileFFI", path: "open_chess_mobileFFI.xcframework"),
        .target(
            name: "OpenChessCore",
            dependencies: ["open_chess_mobileFFI"],
            path: "Sources/OpenChessCore",
            // What the Rust static library calls into: random numbers
            // (getrandom uses Security's SecRandomCopyBytes) and the system.
            linkerSettings: [.linkedFramework("Security"), .linkedFramework("SystemConfiguration")]
        ),
    ]
)
SWIFT

rm -rf "$gen"
echo "$pkg"
